"""Tests for attribution_check.py. This file is exempt from the check itself: its fixtures are attribution."""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT / "shared" / "scripts"))

import attribution_check as ac  # noqa: E402


def write(root: Path, rel: str, text: str) -> None:
    path = root / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def git(root: Path, *args: str) -> None:
    subprocess.run(["git", *args], cwd=root, check=True, capture_output=True)



FLAGGED = [
    "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>",
    "Co-authored-by: GitHub Copilot <copilot@github.com>",
    "\N{ROBOT FACE} Generated with [Claude Code](https://claude.com/claude-code)",
    "This module was generated by ChatGPT.",
    "// AI-generated helper",
    "Generated-by: some-agent",
    "Written with the help of an LLM.",
]
CLEAN = [
    "Co-authored-by: Jane Doe <jane@example.ai>",
    "feat(providers): add a Gemini adapter behind the LLM port",
    "Paginate with a cursor; generated ids use UUIDv7.",
    "The answer is generated by the model the user picked.",
]


@pytest.mark.parametrize("line", FLAGGED)
def test_attribution_flags(line: str) -> None:
    assert ac.scan_text(line), line


@pytest.mark.parametrize("line", CLEAN)
def test_attribution_allows(line: str) -> None:
    assert not ac.scan_text(line), line


def test_attribution_message_file(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    msg = tmp_path / "MSG"
    msg.write_text("feat: x\n\n# Co-Authored-By: Claude (comment line, ignored)\n", encoding="utf-8")
    assert ac.main(["--message-file", str(msg)]) == 0
    msg.write_text("feat: x\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n", encoding="utf-8")
    assert ac.main(["--message-file", str(msg)]) == 1
    assert "AI co-author trailer" in capsys.readouterr().out


def test_attribution_range_checks_messages_and_added_lines(tmp_path: Path, monkeypatch: pytest.MonkeyPatch,
                                                          capsys: pytest.CaptureFixture[str]) -> None:
    git(tmp_path, "init", "-q", "-b", "main")
    git(tmp_path, "config", "user.email", "dev@example.com")
    git(tmp_path, "config", "user.name", "Dev")
    write(tmp_path, "a.txt", "one\n")
    git(tmp_path, "add", ".")
    git(tmp_path, "commit", "-q", "-m", "chore: init")
    write(tmp_path, "a.txt", "one\n// AI-generated helper\n")
    write(tmp_path, "AGENTS.md", "Never add Co-Authored-By: Claude trailers.\n")
    git(tmp_path, "add", ".")
    git(tmp_path, "commit", "-q", "-m", "feat: x\n\nCo-Authored-By: Claude <noreply@anthropic.com>")
    monkeypatch.chdir(tmp_path)
    assert ac.main(["--range", "HEAD~1..HEAD"]) == 1
    out = capsys.readouterr().out
    assert "a.txt:2: 'AI-generated' label" in out
    assert "AI co-author trailer" in out
    assert "AGENTS.md" not in out, "agent instruction files are exempt"
    assert ac.main(["--range", "nonsense"]) == 2
