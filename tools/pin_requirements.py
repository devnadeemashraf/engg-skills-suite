#!/usr/bin/env python3
"""Regenerate the hash-pinned requirements files from PyPI metadata.

Edit the PINS below (exact versions, including transitive dependencies), then run:
    python tools/pin_requirements.py
CI installs with `pip install --require-hashes`, so every file pip might pick is listed.
"""
from __future__ import annotations

import json
import time
import urllib.request
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent

# requirements-dev.txt: validator + tests. Python >= 3.11, so pytest needs no tomli/exceptiongroup.
DEV_PINS = {
    "pyyaml": ("6.0.4", None),
    "pytest": ("9.2.0", None),
    "iniconfig": ("2.3.1", None),
    "packaging": ("26.3", None),
    "pluggy": ("1.7.0", None),
    "pygments": ("2.21.0", None),
    "colorama": ("0.4.6", 'sys_platform == "win32"'),
    # import-linter: runs the compiled Python architecture contract in tests.
    "import-linter": ("2.17", None),
    "grimp": ("3.20", None),
    "click": ("8.5.1", None),
    "rich": ("15.0.0", None),
    "markdown-it-py": ("4.3.0", None),
    "mdurl": ("0.1.2", None),
    # lizard: per-function complexity, parsed by the deep audit's map step.
    "lizard": ("1.26.1", None),
    "pathspec": ("1.1.1", None),
}

# requirements-lint.txt: GitHub Actions security linter (ships as a self-contained wheel).
LINT_PINS = {
    "zizmor": ("1.32.0", None),
}

HEADER = (
    "# Generated by tools/pin_requirements.py from PyPI metadata. Do not edit by hand.\n"
    "# Install with: python -m pip install --require-hashes -r <this file>\n"
)


def fetch_hashes(name: str, version: str, attempts: int = 4) -> list[str]:
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    for attempt in range(1, attempts + 1):
        try:
            with urllib.request.urlopen(url, timeout=30) as resp:
                data = json.load(resp)
            return sorted({f["digests"]["sha256"] for f in data["urls"]})
        except OSError:
            if attempt == attempts:
                raise
            time.sleep(2 * attempt)
    raise AssertionError("unreachable")


def render(pins: dict[str, tuple[str, str | None]]) -> str:
    blocks = []
    for name, (version, marker) in pins.items():
        hashes = fetch_hashes(name, version)
        if not hashes:
            raise SystemExit(f"{name}=={version}: no files on PyPI")
        head = f"{name}=={version}" + (f" ; {marker}" if marker else "")
        blocks.append(" \\\n".join([head] + [f"    --hash=sha256:{h}" for h in hashes]))
    return HEADER + "\n".join(blocks) + "\n"


def main() -> None:
    for filename, pins in (("requirements-dev.txt", DEV_PINS), ("requirements-lint.txt", LINT_PINS)):
        (REPO_ROOT / filename).write_text(render(pins), encoding="utf-8", newline="\n")
        print(f"wrote {filename} ({len(pins)} packages)")


if __name__ == "__main__":
    main()
